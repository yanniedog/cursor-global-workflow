import assert from 'node:assert/strict';
import { startHeadWaitClock, elapsedHeadWait } from './lib/bot-wait-clock.mjs';
const created = '2026-01-01T00:00:00Z';
const now = '2026-09-12T00:00:00Z';
const later = '2026-09-12T00:01:00Z';
const state = { anchor: created, headSha: 'old', waitStartedAt: created };
startHeadWaitClock(state, 'new', false, now);
assert.equal(state.anchor, created);
assert.equal(elapsedHeadWait(state, new Date(created), Date.parse(now)), 0);
state.headSha = 'new';
startHeadWaitClock(state, 'new', false, later);
assert.equal(state.waitStartedAt, now);
assert.equal(elapsedHeadWait(state, new Date(created), Date.parse(later)), 60000);
const migration = { anchor: created };
startHeadWaitClock(migration, 'new', false, now);
assert.equal(migration.anchor, created);
assert.equal(migration.waitStartedAt, now);
startHeadWaitClock(state, 'new', true, later);
assert.equal(state.waitStartedAt, later);
console.log('Head wait clock regression checks passed');
